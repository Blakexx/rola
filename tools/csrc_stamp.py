"""THE CSRC CONTENT HASH AND ITS DEVICE STAMP: the digest of the kernel sources, and the generated header that compiles
it into the binary as a device constant, so a binary proves which sources it was built from.

The build writes the header before it compiles anything and `tools/ratify.py` before it measures anything, from these
functions, so the stamp a gate assembles is the stamp the build assembles. A generated header rather than a define: a
define reaches every unit's command line, so every source edit would rebuild the whole extension instead of the stamp
sites. Standard library only, so the graph's stamp action runs it in its sandbox. Docs:
docs/ratification.md#the-device-stamp-keys-on-the-csrc-content-hash.
"""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path

SRC = Path(__file__).resolve().parents[1] / "csrc" / "rola" / "src"
INC = "csrc_stamp.inc"
#: 60 bits of the digest: the stamp entries return `int64_t`, and a constant folded with other facts leaves room to be
#: folded
BITS = 60


def digest(src: Path = SRC) -> str:
    """The digest of every file under `src` but its markdown, paths and contents: a renamed file moves it."""
    h = hashlib.sha256()
    for path in sorted(src.rglob("*")):
        if path.is_file() and path.suffix != ".md":
            h.update(str(path.relative_to(src)).encode())
            h.update(path.read_bytes())
    return h.hexdigest()


def stamp(d: str) -> int:
    """The device-side value of the digest."""
    return int(d, 16) & ((1 << BITS) - 1)


def header(d: str) -> str:
    """The generated header the stamp sites include."""
    return (f"// GENERATED by tools/csrc_stamp.py -- do not edit, regenerate.\n"
            f"// THE CSRC CONTENT HASH, as a device constant. Written by the build before it compiles\n"
            f"// and by tools/ratify.py before it measures; never checked in.\n"
            f"// See docs/ratification.md#the-device-stamp-keys-on-the-csrc-content-hash.\n"
            f"// sha256(csrc/rola/src) = {d}\n"
            f"#define ROLA_CSRC_STAMP {stamp(d)}LL\n")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--src", type=Path, required=True, help="the kernel sources' root (csrc/rola/src)")
    ap.add_argument("--out", type=Path, required=True, help="the header to write")
    a = ap.parse_args()
    a.out.write_text(header(digest(a.src)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
