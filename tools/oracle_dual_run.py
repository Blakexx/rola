def _levels(types, widths):
    """One softmax routing level per width.

    The oracle takes ALREADY-NORMALIZED simplices, so the activation choice never
    reaches it -- softmax is here because a topology requires one, and matching Tier 1
    keeps the two matrices talking about the same object.
    """
    dense = types.SoftmaxActivation()
    return tuple(types.IndependentRouting(width=w, read=dense, write=dense) for w in widths)


def _call(fn, **kwargs):
    """Call `fn` with the arguments it actually accepts, and only those.

    The protocol compares SEMANTICS across a change that may move the API -- removing
    a solver's iteration count is exactly such a change, and it is one of the things
    under test. Binding by signature is what lets the two sides be asked the same
    question through two different spellings; it is not a fallback, because the
    quantity compared afterwards is unchanged and every dropped argument is one this
    version does not have.
    """
    import inspect

    accepted = inspect.signature(fn).parameters
    return fn(**{k: v for k, v in kwargs.items() if k in accepted})


def emit_producer() -> dict:
    """Every producer quantity, from whichever `rola` is importable."""
    from rola.routing.entmax.reference import entmax, entmax_forward
    from rola.routing.reference import _union_split_with_support, union_split

    #: The old reference's own routing-level iteration count, passed only where the
    #: parameter still exists. `rola/routing/reference.py` used 80 before the swap.
    iters = {"n_iter": 80}

    out: dict[str, torch.Tensor] = {}
    for name, z, mask, alpha in _producer_cells():
        p, support, tau = _call(entmax_forward, z=z, alpha=alpha, dim=-1, mask=mask,
                                **iters)
        out[f"{name}/p"] = p
        out[f"{name}/support"] = support
        out[f"{name}/tau"] = tau
        #: The VJP through the PUBLIC entry point, with a seeded cotangent -- the
        #: backward is half of what a reference promises and the card's backward
        #: conformance depends on it.
        zg = z.clone().requires_grad_(True)
        pv = _call(entmax, z=zg, alpha=alpha, dim=-1, mask=mask, **iters)
        dp = torch.linspace(-1.0, 1.0, pv.numel(), dtype=torch.float64).reshape(pv.shape)
        (dz,) = torch.autograd.grad(pv, zg, grad_outputs=dp)
        out[f"{name}/dz"] = dz

    for name, r, w, mask in _routing_cells():
        read, write = _call(union_split, read_logits=r, write_logits=w, alpha=1.5,
                            mask=mask, **iters)
        out[f"{name}/read"] = read
        out[f"{name}/write"] = write
        #: The PACKED support is captured through the private entry point on
        #: purpose: it is the reference's wire format, and a packing change that the
        #: semantic outputs cannot see is exactly what the kernel would then be
        #: gated against.
        out[f"{name}/packed"] = _call(_union_split_with_support, read_logits=r,
                                      write_logits=w, alpha=1.5, mask=mask, **iters)[2]
    return out


#: the marker for "this input received NO gradient". An empty tensor rather than a
#: zero one, because the whole point of the backward half is that `None` and `0.0`
#: are DIFFERENT answers: `.detach()` at the clock is the oracle's literal spec, and
#: a manufactured graph edge that turns the refusal into a zero is exactly the defect
#: audit finding F1 names. A shape mismatch is then how the comparison reports it.
NO_GRAD = torch.zeros(0, dtype=torch.float64)


def emit_oracle(chunk: int = 0, chunks: int = 1) -> dict:
    """`naive_rola`'s outputs over the structural matrix, forward and backward.

    `chunk`/`chunks` select every `chunks`-th cell. THE INPUTS ARE DRAWN FOR EVERY
    CELL REGARDLESS -- only the oracle call is skipped -- so the generator reaches
    each cell in the same state at every chunk count, and a run split four ways
    compares the same numbers as a run split none ways. Chunking exists for peak
    memory (the backward retains one graph per token) and must not be able to
    change what is measured.
    """
    import rola.routing.types as types
    from rola.ops.naive import naive_rola
    from rola.routing.types import LeafMassDecay, Topology

    out: dict[str, torch.Tensor] = {}
    g = torch.Generator().manual_seed(SEED + 2)

    def simplex(shape):
        x = torch.rand(shape, generator=g, dtype=torch.float64) + 1e-3
        return x / x.sum(dim=-1, keepdim=True)

    #: The structural rectangles, the two `d_v`, decay off and on, and the
    #: tile-boundary/ragged `T` values. Named adversarial corners are mandatory rows,
    #: not options (the card's fixture design).
    #:
    #: THERE IS ONE NORMALIZATION AXIS VALUE, AND THAT IS NOT A NARROWING. `raw` is a
    #: dead axis: `validate_normalization` refuses it, and `naive_rola` calls that
    #: validator on entry, so every `raw` row raised on BOTH sides -- and since the
    #: emit runs before the comparison, one raising row aborted the whole run. This
    #: surface was therefore unrunnable, not merely narrower, for as long as `raw`
    #: has been dead. Reviving `raw` revives its rows here in the same batch.
    normalization = "global"
    index = -1
    for widths in ((64, 64), (8, 8, 8, 16), (4, 4)):
        for d_v in (32, 64):
            for decay_on in (False, True):
                for T in (1, 17, 37, 64):
                    index += 1
                    B, H = 1, 2
                    #: BOUND BY SIGNATURE, because `d_v` left `Topology` for the
                    #: layer. The old side still declares the parameter and
                    #: is handed it; the new side does not and is not. The oracle
                    #: derives `d_v` from `v` on BOTH sides, so the two are asked
                    #: the same question through two spellings -- which is the
                    #: mechanism `_call` exists for.
                    topo = _call(
                        Topology, levels=_levels(types, widths), d_v=d_v)
                    read = tuple(simplex((B, T, H, w)) for w in widths)
                    write = tuple(simplex((B, T, H, w)) for w in widths)
                    v = torch.randn(B, T, H, d_v, generator=g, dtype=torch.float64)
                    g_write = torch.rand(B, T, H, generator=g, dtype=torch.float64) + 0.5
                    g_read = (None if normalization == "global"
                              else torch.rand(B, T, H, generator=g,
                                              dtype=torch.float64) + 0.5)
                    decay = None
                    if decay_on:
                        dials = tuple(
                            torch.rand(H, w, generator=g, dtype=torch.float64)
                            * 0.3 + 0.1 for w in widths)
                        decay = LeafMassDecay(dials=dials)
                    if index % chunks != chunk:
                        continue
                    name = (f"{'x'.join(map(str, widths))}-dv{d_v}-{normalization}-"
                            f"{'decay' if decay_on else 'nodecay'}-T{T}")
                    operands = _differentiable(
                        v=v, g_read=g_read, g_write=g_write, read=read,
                        write=write, dials=None if decay is None else decay.dials)
                    y, state = _call(
                        naive_rola, v=v, read_levels=read, write_levels=write,
                        g_read=g_read, g_write=g_write, topology=topo, decay=decay,
                        normalization=normalization, output_final_state=True)
                    out[f"{name}/y"] = y
                    out[f"{name}/state"] = state
                    out.update(_backward(name, y, state, operands))
    return out


def _differentiable(**named):
    """Flatten the oracle's operands into `{key: tensor}`, marking each for grad.

    Tuples are expanded per level; `None` operands (no read gain under `global`,
    no dials without decay) simply do not appear, so a cell's key set states which
    operands that cell HAS.
    """
    flat: dict[str, torch.Tensor] = {}
    for key, value in named.items():
        if value is None:
            continue
        items = value if isinstance(value, tuple) else (value,)
        for index, tensor in enumerate(items):
            label = key if not isinstance(value, tuple) else f"{key}{index}"
            tensor.requires_grad_(True)
            flat[label] = tensor
    return flat


def _backward(name: str, y, state, operands: dict) -> dict:
    """P3: one seeded VJP per cell, every operand, `None` recorded as `None`.

    The cotangents are `linspace`, not random: the generator's state must not
    depend on how many cells ran before this one, or a matrix edit silently
    re-seeds every backward in the run.
    """
    dy = torch.linspace(-1.0, 1.0, y.numel(), dtype=torch.float64).reshape(y.shape)
    dstate = torch.linspace(0.25, -0.75, state.numel(), dtype=torch.float64).reshape(state.shape)
    keys = sorted(operands)
    grads = torch.autograd.grad(
        outputs=(y, state), inputs=[operands[k] for k in keys],
        grad_outputs=(dy, dstate), allow_unused=True)
    return {f"{name}/d{key}": (NO_GRAD if grad is None else grad.detach())
            for key, grad in zip(keys, grads)}


#: `emit_producer` takes no chunk arguments: its matrix is 90 small quantities and
#: splitting it would buy nothing. The dispatch passes them only where they exist.
SURFACES = {"producer": emit_producer, "oracle": emit_oracle}


def _emit(surface: str, chunk: int, chunks: int) -> dict:
    if surface == "oracle":
        return emit_oracle(chunk=chunk, chunks=chunks)
    if chunk:
        return {}
    return emit_producer()


