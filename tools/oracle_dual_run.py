def apply_mutant(kind: str) -> None:
    """Inject a known defect into the NEW side. The run MUST then fail.

    Each mutant is one of the blind spots the protocol exists to cover, so a mutant
    that does not fail names a hole in the comparison rather than a harmless change.
    """
    if kind == "strides":
        #: THE LEAF-ADDRESS MAP, perturbed where the oracle actually reads it: its
        #: OWN derivation (`rola/ops/naive.py::_radix_strides`).
        #:
        #: This mutant used to reverse `Topology.radix_strides`, because the oracle
        #: imported it. It no longer does, so that perturbation
        #: now moves nothing here BY DESIGN -- and the inverted claim, that a wrong
        #: production stride leaves the oracle unmoved and therefore DISAGREEING
        #: with the kernel, is asserted where it belongs, in
        #: `tests/oracle/test_oracle_independence.py`. What this file must still be
        #: able to see is a change to the address map the oracle uses.
        import rola.ops.naive as naive

        original = naive._radix_strides
        naive._radix_strides = lambda widths: tuple(original(widths)[::-1])
    elif kind == "eps":
        #: The readout's epsilon changes the FUNCTION, not its accuracy.
        import rola.ops.naive as naive

        #: `eps` is KEYWORD-ONLY, so it lives in `__kwdefaults__`. Perturbing the
        #: default rather than the call sites is deliberate: it is the same thing a
        #: careless edit to the constant would do.
        naive.naive_rola.__kwdefaults__["eps"] = 2e-5
    elif kind == "clock":
        #: THE DETACHMENT AT THE CLOCK, removed. `c = stop_gradient(prod_l
        #: p_write_stored)` is the spec's own wording, so a gradient reaching the
        #: stored levels is a semantic change that the FORWARD cannot see at all --
        #: this is the mutant that says whether the backward half has teeth.
        #:
        #: Source-level, because the detachment is an expression inside the
        #: recurrence rather than a name that can be rebound. The module is
        #: re-executed in its own globals with the call removed; the count assert
        #: is what stops a future edit from making the mutant a no-op.
        import rola.ops.naive as naive

        source = Path(naive.__file__).read_text()
        if source.count(".detach()") != 1:
            raise SystemExit(
                f"the `clock` mutant expects exactly one `.detach()` in "
                f"{naive.__file__}, found {source.count('.detach()')}")
        namespace = dict(naive.__dict__)
        exec(compile(source.replace(".detach()", ""), naive.__file__, "exec"), namespace)
        naive.naive_rola = namespace["naive_rola"]
    elif kind == "support":
        #: One entry pushed out of the support: the claim P4 makes with no tolerance.
        import rola.routing.entmax.reference as ref

        inner = ref.entmax_forward

        def clipped(z, alpha, dim=-1, mask=None, **kw):
            p, support, tau = inner(z, alpha, dim=dim, mask=mask, **kw)
            flat = support.reshape(-1, support.shape[-1])
            for row in range(flat.shape[0]):
                idx = flat[row].nonzero()
                if idx.numel() > 1:
                    flat[row, idx[-1]] = False
                    break
            return p, support, tau

        ref.entmax_forward = clipped
    else:
        raise SystemExit(f"unknown mutant {kind!r}; known: strides, eps, clock, support")
    print(f"MUTANT ACTIVE: {kind}  (this run MUST fail)")


