"""THE DUAL-RUN PROTOCOL: no change to the crown jewels lands without it.

    python tools/oracle_dual_run.py --surface producer --against HEAD~1
    python tools/oracle_dual_run.py --surface oracle   --against HEAD~1 --json run.json
    python tools/oracle_dual_run.py --surface producer --against HEAD~1 --mutate strides

The oracle pair -- `rola/ops/naive.py` and the routing references it composes with --
is what every Tier 1 gate is anchored to. A change to it cannot be reviewed by
reading the diff, because the question is never "is the new code reasonable" but "does
it compute the same function". So both versions are RUN, over a declared matrix, and
compared.

**THE OLD SIDE IS THE PARENT COMMIT'S REAL CODE.** It is checked out into a throwaway
git worktree and run in a SUBPROCESS with that tree on `PYTHONPATH` -- never
re-implemented, never copy-pasted, and never imported under an alias into this
process, where one stale `sys.modules` entry would silently compare a tree against
itself. Everything CPU and fp64: the references are pure torch, so no build is
involved and no device is touched.

**THE MATRIX IS GENERATED BY THIS FILE, AT THIS COMMIT, FOR BOTH SIDES.** The old
tree supplies the library; it never supplies the inputs. Same generator, same seeds,
one library swapped -- which is the only construction under which a difference is
attributable.

Two surfaces, because the two steps of the decomposition have different contracts:

* `--surface producer` -- the routing reference: entmax values, the support SET, the
  VJP, and the composed `routing_factors` / `union_split`. Compared under the
  PRODUCER CONTRACT: `max|dp| <= 1e-13`, `max|dz| <= 1e-13`, and support sets
  equal EXACTLY. Bit-identity is deliberately NOT required here -- the declared
  purpose of that step is to replace a bisection with a third party's closed form,
  so agreement to 1e-14 is the result, and the support-set equality is the claim with
  teeth (a threshold that moves by one entry is a routing change, not rounding).
* `--surface oracle` -- `naive_rola` itself, FORWARD AND BACKWARD. Compared BY
  BIT-IDENTITY: both sides run fp64 on identical inputs, so a rewrite that only
  nearly reproduces the old one has changed the definition. Declared exceptions are
  named on the command line (exact key, or a `fnmatch` pattern) and asserted
  individually; anything undeclared is a failure.

**THE BACKWARD HALF IS P3, AND IT IS NOT OPTIONAL.** A seeded VJP per cell over every
operand, with `None` recorded as `None` rather than coerced to zeros -- because the
oracle's `.detach()` at the clock is its literal spec, and the difference between "no
gradient" and "a zero gradient" is precisely what a manufactured graph edge hides. The
clock's detachment is observed through the WRITE levels, which under the bf16-bundle
ruling are the stored form: the `clock` mutant removes the `.detach()` and the write
levels' gradient moves.

**P5, NON-VACUITY.** `--mutate` injects a known defect into the NEW side and the run
must FAIL. A protocol that cannot fail is not a protocol, and this one is the gate
that stands between a quiet oracle change and every Tier 1 claim in the repository.

**P7, THE COUNT.** Every run asserts it compared at least `MINIMUM_COMPARISONS`
quantities and fails RED otherwise: a gate that cannot run must say so, not report a
verdict over whatever survived.
"""
