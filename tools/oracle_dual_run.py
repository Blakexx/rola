def bind_library(root: Path, label: str) -> Path:
    """Import `rola` FROM `root`, and refuse to run if that is not what happened.

    **THIS IS THE TRAP THAT MAKES A DUAL RUN VACUOUS, AND IT IS REAL, NOT
    HYPOTHETICAL.** `rola` is installed editable, so `import rola` resolves through
    the install's path entry -- which names the CANONICAL checkout. Run as a script
    from a worktree, `sys.path[0]` is the script's own directory (`tools/`), the
    worktree's root is on no path at all, and both sides of the protocol quietly
    import the same canonical tree. Every comparison then passes, having compared
    nothing. Measured: from a sibling worktree (`/path/to/worktrees/<name>`),
    `python tools/...py` imported the CANONICAL checkout's `rola/__init__.py`
    instead of its own.

    The library each side must use is therefore named explicitly and CHECKED after
    the import, not merely arranged for. A path insertion that fails to take effect
    is exactly as silent as no insertion at all; the assertion is what makes it
    loud, and the printed path is what puts it in the record.
    """
    root = root.resolve()
    sys.path.insert(0, str(root))
    import rola

    actual = Path(rola.__file__).resolve()
    if root not in actual.parents:
        raise SystemExit(
            f"the {label} side imported {actual}, not the tree at {root} -- the "
            f"comparison would be between that tree and itself")
    print(f"{label} library: {actual.parent}")
    return actual.parent


#: the thresholds, from the measured agreement with one decade of headroom
#: (workflows/refactor/p07_audit.md section 3.2: worst 1.42e-14 forward, 6.66e-16 VJP).
#: The SUPPORT-SET claim carries no tolerance at all, by construction.
PRODUCER_ATOL = 1e-13

#: The bound a REASSOCIATED quantity is held to instead of bit-identity.
#:
#: Reassociation is the one difference a rewrite can legitimately introduce: the
#: same sum, added up in a different order. Its size is bounded by the length of
#: the sum times the unit roundoff, and the longest sum here is over the leaves,
#: `N <= 4096` in the matrix -- so `N * 2^-53 = 4.5e-13`. `1e-12` is that with a
#: factor of two of headroom, and it is RELATIVE, because the quantities span many
#: decades. A difference that does not fit is not reassociation.
REASSOCIATION_RTOL = 1e-12

#: fp64 seeds. Fixed here rather than passed in: a matrix whose inputs depend on the
#: caller is a matrix two runs can disagree about without either being wrong.
SEED = 20260805

#: How many slices the matrix runs in by default.
#:
#: THE UNCHUNKED RUN IS A HOST HAZARD, not merely a large one. The backward retains
#: one autograd graph per token per cell and the largest cells are `64x64` (N = 4096
#: leaves) at `T = 64`; run whole, the protocol peaked near 18 GB on a 23 GB machine
#: shared with build lanes and drove it into swap twice. Measured peak RSS of the
#: whole run (parent plus the old side), against an unchanged tree:
#:
#:     chunks=1   ~18 GB    (froze the host)
#:     chunks=4    13.0 GB  0:58
#:     chunks=16    4.6 GB  1:49
#:
#: 16 buys the headroom at 51 s. CHUNKING PROVABLY CANNOT CHANGE THE NUMBERS: the
#: inputs are drawn for every cell at every chunk count and only the oracle call is
#: skipped, and it is checked rather than argued -- the union over `chunks=4` and the
#: union over `chunks=8` are the same 1328 quantities, bit-identical, 0 mismatches.
DEFAULT_CHUNKS = 16

#: THE FLOOR ON WHAT A RUN MUST HAVE COMPARED, per surface, and a run that produces
#: fewer quantities FAILS RED. Measured (`oracle` 640, `producer` 162) and
#: raised whenever the matrix grows: a gate must prove it COMPARED, because a matrix
#: that quietly stopped emitting rows -- an axis that raises in the generator, a cell
#: that returns nothing -- reports PASS over whatever survived, and this protocol is
#: what stands between a quiet oracle change and every Tier 1 claim in the tree. The
#: precedent is real: the `oracle` surface was UNRUNNABLE for a window after `raw`
#: died and nothing said so.
#:
#: LOWERED ONCE, from `oracle` 640 to 512: the `write_levels_stored`
#: operand left the oracle's signature under R1 (the producer emits the stored form),
#: and the 128 `*/dstored{0,1}` gradients it contributed were `None` on both sides by
#: construction. The shim that kept passing it existed to span exactly the python
#: commits and is gone with it; what remains is the same matrix minus a vacuous
#: operand, which is why this is a legitimate shrink and not a lost row.
MINIMUM_COMPARISONS = {"oracle": 512, "producer": 162}


