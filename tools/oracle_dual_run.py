def _producer_cells():
    """`(name, logits, mask, alpha)` over logit scale x width x masking.

    The scales are the audit's: 0.5 is a nearly-dense simplex, 3 is the working
    regime, 30 is where a bisection's finite iteration count shows and where two
    implementations are most likely to disagree about the support boundary.
    """
    g = torch.Generator().manual_seed(SEED)
    for width in (3, 16, 256):
        for scale in (0.5, 3.0, 30.0):
            z = torch.randn(8, width, generator=g, dtype=torch.float64) * scale
            for masked in (False, True):
                mask = None
                if masked:
                    mask = torch.ones(8, width, dtype=torch.bool)
                    #: A ragged mask, not a uniform one: padding past `b` is what the
                    #: kernel's `bmask` does, and a uniform mask would exercise none
                    #: of the boundary the mask exists for.
                    for row in range(8):
                        mask[row, max(1, width - row % width):] = False
                for alpha in (1.5, 2.0):
                    yield (f"w{width}-s{scale}-{'masked' if masked else 'dense'}-a{alpha}",
                           z.clone(), mask, alpha)


def _routing_cells():
    """`(name, read_logits, write_logits, mask)` for the COMPOSED reference."""
    g = torch.Generator().manual_seed(SEED + 1)
    for width in (4, 16):
        for scale in (0.5, 3.0, 30.0):
            r = torch.randn(2, 5, width, generator=g, dtype=torch.float64) * scale
            w = torch.randn(2, 5, width, generator=g, dtype=torch.float64) * scale
            yield (f"union-w{width}-s{scale}", r, w, None)


