def _excepted(key: str, exceptions) -> bool:
    """A declared P2 exception matches by exact key or by `fnmatch` pattern.

    Patterns exist because an exception is usually a QUANTITY -- one gradient across
    every cell -- rather than one cell, and ninety-six spellings of the same
    declaration is a declaration nobody reads.
    """
    return any(key == e or fnmatch.fnmatch(key, e) for e in exceptions)


def _matches(key: str, patterns) -> bool:
    """Same matching rule, for the reassociation register."""
    return any(key == p or fnmatch.fnmatch(key, p) for p in patterns)


def compare(old: dict, new: dict, *, surface: str, exceptions: set,
            reassociated: set = frozenset()) -> dict:
    """One chunk's tally: how many quantities, the worst difference, the failures."""
    only_old = sorted(k for k in set(old) - set(new) if not _excepted(k, exceptions))
    only_new = sorted(k for k in set(new) - set(old) if not _excepted(k, exceptions))
    if only_old or only_new:
        return {"count": len(old), "worst": {"value": 0.0, "key": None},
                "failures": [(key, "answered by only one side")
                             for key in only_old + only_new]}

    worst = {"value": 0.0, "key": None}
    failures = []
    for key in sorted(old):
        a, b = old[key], new[key]
        quantity = key.rsplit("/", 1)[-1]
        if a.shape != b.shape:
            if not _excepted(key, exceptions):
                #: A gradient that appeared or vanished lands here, since NO_GRAD is
                #: the empty tensor: the message names the transition rather than a
                #: number, which is the only useful thing to say about it.
                failures.append((key, f"shape {tuple(a.shape)} -> {tuple(b.shape)}"))
            continue
        if a.dtype == torch.bool or quantity in ("support", "packed"):
            #: NO TOLERANCE. A support set or a packed word is a discrete claim; one
            #: entry moving is a routing change, not a rounding difference.
            if not torch.equal(a, b):
                differing = int((a != b).sum())
                failures.append((key, f"{differing} discrete entr(ies) differ"))
            continue
        if a.numel() == 0:
            #: Both sides answered `None` (the shapes already agree, so this is not a
            #: transition). There is no continuous quantity to compare and `max()`
            #: has no answer on an empty tensor; agreeing refusals agree.
            continue
        delta = (a.double() - b.double()).abs().max().item()
        if delta > worst["value"]:
            worst = {"value": delta, "key": key}
        if _matches(key, reassociated):
            #: DECLARED REASSOCIATION. Not an exemption: the quantity still has to
            #: agree, just under the bound a reordered sum can produce rather than
            #: under bit-identity. Anything larger is a changed definition wearing a
            #: rounding difference's clothes.
            scale = max(float(a.abs().max()), float(b.abs().max()), 1.0)
            if delta > REASSOCIATION_RTOL * scale:
                failures.append(
                    (key, f"max|d| = {delta:.3e} exceeds the reassociation bound "
                          f"{REASSOCIATION_RTOL * scale:.3e}"))
            continue
        if surface == "oracle" and not _excepted(key, exceptions):
            if not torch.equal(a, b):
                failures.append((key, f"not bit-identical, max|d| = {delta:.3e}"))
        elif delta > PRODUCER_ATOL:
            failures.append((key, f"max|d| = {delta:.3e} > {PRODUCER_ATOL:.0e}"))

    return {"count": len(old), "worst": worst, "failures": failures}


#: The OLD side's subprocess environment. `TORCHINDUCTOR_COMPILE_THREADS` is
#: pinned because torch fans out one compile worker per core on import and the
#: protocol runs two interpreters at once on a 23 GB host shared with build lanes;
#: nothing here is compiled, so the workers were pure overhead. `PATH` stays
#: minimal so the old tree cannot pick up a tool from the caller's shell.
OLD_SIDE_ENV = {"PATH": "/usr/bin:/bin", "TORCHINDUCTOR_COMPILE_THREADS": "4",
                "OMP_NUM_THREADS": "4"}


@contextlib.contextmanager
def _old_tree(ref: str):
    """`ref` checked out into a throwaway worktree, for the life of the run.

    One worktree for every chunk: checking out again per chunk would be the same
    tree fetched N times, and a tree that changed between chunks would silently
    make the chunks incomparable.
    """
    with tempfile.TemporaryDirectory(prefix="rola_dualrun_") as tmp:
        tree = Path(tmp) / "old"
        subprocess.run(["git", "-C", str(ROOT), "worktree", "add", "--detach",
                        str(tree), ref], check=True, capture_output=True, text=True)
        try:
            yield tree
        finally:
            subprocess.run(["git", "-C", str(ROOT), "worktree", "remove", "--force",
                            str(tree)], check=False, capture_output=True)


def _emit_old(tree: Path, ref: str, surface: str, out_path: Path,
              chunk: int, chunks: int) -> None:
    """Run this same file inside the old tree, against the old tree's library."""
    proc = subprocess.run(
        [sys.executable, str(Path(__file__).resolve()), "--surface", surface,
         "--emit", str(out_path), "--chunk", str(chunk), "--chunks", str(chunks),
         "--library", str(tree)],
        cwd=str(tree), env={"PYTHONPATH": str(tree), **OLD_SIDE_ENV},
        capture_output=True, text=True)
    if proc.returncode != 0:
        sys.stderr.write(proc.stdout + proc.stderr)
        raise SystemExit(f"the OLD side ({ref}) failed to run (chunk {chunk}/{chunks})")
    #: The old side's bound library is echoed once, on the first slice: the record
    #: has to name BOTH trees, or "the old side imported the old tree" is a claim
    #: about the code rather than about the run.
    if chunk == 0:
        for line in proc.stdout.splitlines():
            if line.startswith("OLD library:"):
                print(line)


def report(surface: str, tallies: list, exceptions: set,
           reassociated: set = frozenset()) -> bool:
    """One verdict over every chunk. A chunked run reads exactly like an unchunked one."""
    count = sum(t["count"] for t in tallies)
    worst = max((t["worst"] for t in tallies), key=lambda w: w["value"],
                default={"value": 0.0, "key": None})
    failures = [item for t in tallies for item in t["failures"]]
    rule = ("BIT-IDENTITY" if surface == "oracle"
            else f"producer contract (atol {PRODUCER_ATOL:.0e}, support sets exact)")
    floor = MINIMUM_COMPARISONS[surface]
    print(f"\n{count} quantities compared under {rule} (floor {floor})")
    print(f"worst continuous difference: {worst['value']:.3e}"
          + (f"  at {worst['key']}" if worst["key"] else ""))
    if exceptions:
        print(f"declared exceptions ({len(exceptions)}): {sorted(exceptions)}")
    if reassociated:
        print(f"declared reassociations ({len(reassociated)}, held to "
              f"{REASSOCIATION_RTOL:.0e} relative): {sorted(reassociated)}")
    if count < floor:
        print(f"\nFAIL  the run compared {count} quantities, below the {surface} "
              f"surface's floor of {floor}: this gate did not gate. Either the matrix "
              "lost rows (find them) or it legitimately shrank (move the floor, in the "
              "same commit, with the reason).")
        return False
    if failures:
        print(f"\nFAIL  {len(failures)} quantit(ies) disagree:")
        for key, why in failures[:12]:
            print(f"        {key}: {why}")
        if len(failures) > 12:
            print(f"        ... and {len(failures) - 12} more")
        return False
    print("PASS  dual run")
    return True


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--surface", choices=sorted(SURFACES), required=True)
    ap.add_argument("--against", metavar="REF",
                    help="the commit whose oracle is the OLD side (e.g. HEAD~1)")
    ap.add_argument("--emit", metavar="PATH",
                    help="internal: write THIS tree's side and exit")
    ap.add_argument("--chunk", type=int, default=0, help="internal: which slice to emit")
    ap.add_argument("--library", metavar="TREE",
                    help="internal: the tree whose `rola` this side must import")
    ap.add_argument("--chunks", type=int, default=DEFAULT_CHUNKS,
                    help=f"slices to run the matrix in, one at a time "
                         f"(default {DEFAULT_CHUNKS}); bounds peak memory, "
                         f"changes nothing measured")
    ap.add_argument("--mutate", metavar="KIND",
                    help="P5: inject a known defect into the NEW side; the run must fail")
    ap.add_argument("--except", dest="exceptions", action="append", default=[],
                    metavar="KEY", help="a declared P2 exception (key or fnmatch), repeatable")
    ap.add_argument("--reassociated", action="append", default=[], metavar="KEY",
                    help="a quantity whose sum is reordered by the change under test: "
                         "held to REASSOCIATION_RTOL instead of bit-identity, never exempt")
    ap.add_argument("--json", metavar="PATH", help="write the record")
    a = ap.parse_args()

    if a.emit:
        bind_library(Path(a.library) if a.library else ROOT, "OLD" if a.library else "NEW")
        torch.save(_emit(a.surface, a.chunk, a.chunks), a.emit)
        return 0
    if not a.against:
        raise SystemExit("--against REF is required (the OLD side is a real commit)")
    if a.chunks < 1:
        raise SystemExit("--chunks must be at least 1")

    #: BEFORE the mutant, which imports `rola` to patch it: a mutant applied to the
    #: wrong tree is a mutant applied to the OLD side as well.
    bind_library(ROOT, "NEW")
    if a.mutate:
        apply_mutant(a.mutate)

    exceptions = set(a.exceptions)
    print(f"OLD = {a.against}   NEW = working tree   surface = {a.surface}"
          + (f"   chunks = {a.chunks}" if a.chunks > 1 else ""))
    tallies = []
    with _old_tree(a.against) as tree:
        for chunk in range(a.chunks):
            #: ONE CHUNK LIVE AT A TIME, on both sides. The old side's dict is
            #: dropped before the next subprocess starts and the new side's before
            #: the next chunk is built, so peak memory is the largest slice rather
            #: than the whole matrix twice.
            with tempfile.TemporaryDirectory(prefix="rola_dualrun_out_") as tmp:
                old_path = Path(tmp) / "old.pt"
                _emit_old(tree, a.against, a.surface, old_path, chunk, a.chunks)
                old = torch.load(old_path, weights_only=False)
            new = _emit(a.surface, chunk, a.chunks)
            tallies.append(compare(old, new, surface=a.surface, exceptions=exceptions,
                                   reassociated=set(a.reassociated)))
            del old, new

    ok = report(a.surface, tallies, exceptions, set(a.reassociated))
    if a.mutate:
        #: The mutant inverts the verdict: a mutant run that PASSES means the
        #: comparison is blind to the defect, which is the failure being tested for.
        if ok:
            print(f"\nP5 FAILED: the protocol PASSED with the {a.mutate!r} mutant "
                  f"active, so it cannot see that class of defect")
            return 1
        print(f"\nP5 PASSED: the protocol rejects the {a.mutate!r} mutant")
        ok = True

    if a.json:
        Path(a.json).write_text(json.dumps(
            {"old": a.against, "surface": a.surface, "mutant": a.mutate,
             "exceptions": sorted(exceptions), "chunks": a.chunks,
             "reassociated": sorted(set(a.reassociated)),
             #: EVERY failure, not the twelve that fit on a screen: the record is
             #: what a reviewer audits, and a truncated one cannot be joined to the
             #: tree.
             "failures": [[k, why] for t in tallies for k, why in t["failures"]],
             "quantities": sum(t["count"] for t in tallies),
             "worst": max((t["worst"]["value"] for t in tallies), default=0.0),
             "passed": ok}, indent=1, sort_keys=True) + "\n")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
