"""THE HARDWARE CONFIGURATION, READ FROM ITS ONE FILE: `csrc/rola/src/common/hardware.json` holds every architecture's
defaults (capabilities and rates) and every product's overrides, each rate with its source. This module generates
`common/hardware.cuh` from it (the capability rows, read at compile time), resolves a product's rates (its overrides
over its architecture's defaults, for run time), checks that the header is current and that every source holds -- a
measured rate matches the lab record it names, on the product it names. Stdlib only (no `rola`, no GPU), so the lint runs it. docs/internals/common/hardware.md.

    python -m measure.hardware [--product rtx3080ti | --arch sm_80]   # the resolved rates
    python -m measure.hardware --write                                # regenerate the header
    python -m measure.hardware --check                                # the gate
"""
from __future__ import annotations

import json
import sys
from dataclasses import dataclass
from pathlib import Path

from measure.hw_profile import slugify_gpu

ROOT = Path(__file__).absolute().parents[1]
COMMON = ROOT / "csrc" / "rola" / "src" / "common"
CONFIG = COMMON / "hardware.json"
HEADER = COMMON / "hardware.cuh"
RESULTS = ROOT / "measure" / "lab" / "results"
MANIFESTS = ROOT / "tools" / "manifests"
#: the rates a built architecture must resolve: its pipes' (the schedulers, the issue, a shared wavefront and the
#: shared atomics), which the phase floors (`tools/overlap_gate.py`), the pipe model and the budgets' forms read
CHOICE = ("schedulers", "issue", "wavefront", "atomic", "atomic_wavefront")
SOURCES = ("measured", "documented", "announced")
#: a measured rate may differ from its record's median by its own rounding and no more
TOLERANCE = 0.002
#: the architecture families, in the order `Family` numbers them (docs/internals/common/hardware.md#families)
FAMILIES = ("ampere", "hopper", "blackwell")
#: the build traits a product may override (each distinct set is a build variant)
BUILD_TRAITS = ("window",)


def load() -> dict:
    return json.loads(CONFIG.read_text())


def cc_of(arch: str) -> int:
    return int(arch.removeprefix("sm_")) * 10


def tabulated(cfg: dict | None = None) -> list[str]:
    """The architectures with a capability row, by compute capability."""
    return sorted((cfg or load())["arch"], key=cc_of)


def _camel(name: str) -> str:
    return "k" + "".join(part[:1].upper() + part[1:] for part in name.split("_"))


def _value(v) -> str:
    return ("true" if v else "false") if isinstance(v, bool) else str(v)


def header(cfg: dict | None = None) -> str:
    """`common/hardware.cuh`'s text: the Caps row of every architecture, the MMA kinds a product's quanta index, and the
    MMA rates in quanta of every architecture and product that tabulates them all."""
    cfg = cfg or load()
    schema = cfg["schema"]["caps"]
    out = ["// csrc/rola/src/common/hardware.cuh -- GENERATED by `python -m measure.hardware --write` from common/hardware.json",
           "// (edit that, not this). see docs/internals/common/hardware.md",
           "#pragma once", "", "// clang-format off", "namespace denseref {", "namespace arch {", "", "struct Caps {"]
    for field in schema:
        out.append(f"  {field['type']} {field['name']};" + (f"  // {field['doc']}" if field["doc"] else ""))
    out += ["};", "", "//: THE TABULATED SET -- see docs/internals/common/arch_caps.md#tabulated",
            "constexpr bool tabulated(int cc) {",
            "  return " + " || ".join(f"cc == {cc_of(a)}" for a in tabulated(cfg)) + ";", "}", "",
            "constexpr Caps caps_of(int cc) {"]
    for arch in tabulated(cfg):
        row = cfg["arch"][arch]
        inits = [f".cc = {cc_of(arch)}"] + [f".{f['name']} = {_value(row['caps'][f['name']])}"
                                             for f in schema if f["name"] != "cc"]
        lines, line = [], ""
        for init in inits:
            if line and len(line) + len(init) + 2 > 108:
                lines.append(line + ",")
                line = ""
            line = f"{line}, {init}" if line else init
        lines.append(line)
        if "note" in row:
            out.append(f"  // {arch}: {row['note']}")
        out.append(f"  if (cc == {cc_of(arch)})")
        out.append("    return Caps{" + lines[0])
        out += [f"                {text}" for text in lines[1:]]
        out[-1] += "};"
    kinds = cfg["schema"]["mma"]
    out += ["  return Caps{};", "}", ""]
    out += _build_lines(cfg)
    out += ["//: the MMA kinds, in the order a product's quanta carry their rates (`kMmaRows`' columns)",
            "enum Mma : int { " + ", ".join(_camel(k) for k in kinds) + ", kMmaKinds };", "",
            "//: THE MMA RATES a scheduler in quanta, read at run time -- see docs/internals/common/hardware.md#consumers",
            "struct MmaRow {", "  int cc;", "  const char* product;  // its product row's slug; nullptr, the architecture's",
            "  long long mma[kMmaKinds];", "};", "",
            "inline constexpr MmaRow kMmaRows[] = {"]

    rows = [(arch, None) for arch in tabulated(cfg)] + [(row["arch"], slug) for slug, row in cfg["product"].items()]
    for arch, product in rows:
        rates = resolve(arch=arch, product=product, cfg=cfg)
        if not all(f"mma.{k}" in rates for k in kinds):
            continue
        slug = f'"{product}"' if product else "nullptr"
        out.append(f"  {{{cc_of(arch)}, {slug}, {{" + ", ".join(str(quantum(rates[f'mma.{k}'].cycles))
                                                            for k in kinds) + "}},")
    out += ["};", "", "}  // namespace arch", "}  // namespace denseref", "", "// clang-format on", ""]
    return "\n".join(out)


def builds(cfg: dict | None = None) -> list[tuple[str, int, dict]]:
    """Every build: (architecture, variant, traits). Variant 0 is the architecture's own row; each distinct product
    override set over it is the next variant, so products equal in build traits share one."""
    cfg = cfg or load()
    out = []
    for arch in tabulated(cfg):
        base = {"window": 0, **cfg["arch"][arch]["build"]}
        out.append((arch, 0, base))
        seen = [base]
        for slug in sorted(cfg["product"]):
            row = cfg["product"][slug]
            traits = {**base, **row.get("build", {})}
            if row["arch"] == arch and traits not in seen:
                seen.append(traits)
                out.append((arch, len(seen) - 1, traits))
    return out


def builds_header(archs: list[str]) -> str:
    """`build/generated/builds.inc`: the builds a binary of these architectures (`["80", "86"]`) carries, every variant
    of each -- the set `common/select.cuh`'s `build_switch` branches over (docs/internals/common/select.md#carried)."""
    cfg = load()
    want = {f"sm_{a}" for a in archs}
    unknown = sorted(want - set(cfg["arch"]))
    if unknown:
        raise SystemExit(f"builds: {', '.join(unknown)} has no row in {CONFIG.name}")
    cases = " ".join(f"F({cc_of(a)}, {v})" for a, v, _ in builds(cfg) if a in want)
    return ("// GENERATED by measure/hardware.py (builds_header) -- do not edit, regenerate.\n"
            "// THE BUILDS THIS BINARY CARRIES. see docs/internals/common/select.md#carried\n"
            "#pragma once\n"
            f"#define ROLA_BUILDS(F) {cases}\n")


def variant_of(product: str, cfg: dict | None = None) -> int:
    """The build variant a product runs: the one whose traits are its architecture's under its own overrides."""
    cfg = cfg or load()
    row = cfg["product"][product]
    traits = {"window": 0, **cfg["arch"][row["arch"]]["build"], **row.get("build", {})}
    return next(v for a, v, t in builds(cfg) if a == row["arch"] and t == traits)


def _build_lines(cfg: dict) -> list[str]:
    """The families, the build key, each build's traits and the product table, as `hardware.cuh` carries them."""
    out = ["//: THE ARCHITECTURE FAMILIES -- see docs/internals/common/hardware.md#families",
           "enum class Family : int { " + ", ".join(_camel(f) for f in FAMILIES) + " };", "",
           "//: A BUILD: the key a kernel compiles at -- its image's compute capability and its variant (products equal",
           "//: in build traits share one). see docs/internals/common/hardware.md#builds",
           "struct Build {", "  int cc;", "  int variant;", "};", "",
           "//: A BUILD'S TRAITS: what a kernel's plan reads. see docs/internals/common/hardware.md#traits",
           "struct Traits {", "  Family family;", "  int window;  // W, a card's: docs/internals/common/window.md",
           "  Caps caps;", "};", "",
           "constexpr Traits traits_of(Build b) {"]
    for arch, variant, traits in builds(cfg):
        out.append(f"  if (b.cc == {cc_of(arch)} && b.variant == {variant})")
        out.append(f"    return Traits{{Family::{_camel(traits['family'])}, {traits['window']}, "
                   f"caps_of({cc_of(arch)})}};")
    out += ["  return Traits{};", "}", "",
            "//: A BUILD AS A TYPE, the form a kernel takes it in (a kernel's class-type template argument must be a",
            "//: type's: docs/internals/common/hardware.md#build-tag)",
            "template <Build B>", "struct BuildTag {", "  static constexpr Build build = B;",
            "  static constexpr Traits traits = traits_of(B);", "};", "",
            "//: THE PRODUCTS: a device's product by its name's slug, and the build variant it runs -- see",
            "//: docs/internals/common/hardware.md#products",
            "struct ProductRow {", "  int cc;", "  const char* slug;", "  int variant;", "};", "",
            "inline constexpr ProductRow kProducts[] = {"]
    for slug in sorted(cfg["product"]):
        out.append(f'  {{{cc_of(cfg["product"][slug]["arch"])}, "{slug}", {variant_of(slug, cfg)}}},')
    return out + ["};", ""]


@dataclass(frozen=True)
class Rate:
    cycles: float
    kind: str
    where: str
    row: str
    on: str


def _flatten(rates: dict, prefix: str = "") -> dict[str, dict]:
    out = {}
    for key, value in rates.items():
        name = f"{prefix}{key}"
        if "cycles" in value:
            out[name] = value
        else:
            out.update(_flatten(value, f"{name}."))
    return out


def _rate(entry: dict, on: str) -> Rate:
    kind = next(k for k in SOURCES if k in entry)
    return Rate(float(entry["cycles"]), kind, entry[kind], entry.get("row", ""), entry.get("on", on))


def resolve(arch: str | None = None, product: str | None = None, cfg: dict | None = None) -> dict[str, Rate]:
    """A product's rates (its architecture's defaults under its own overrides), or an architecture's defaults alone:
    `{field: Rate}` with fields `issue`, `mma.hmma_f16_f32`, `tax.hmma_f16_f32.fp32`, ..."""
    cfg = cfg or load()
    if product is not None:
        arch = cfg["product"][product]["arch"]
    rates = {k: _rate(v, "") for k, v in _flatten(cfg["arch"][arch].get("rates", {})).items()}
    if product is not None:
        rates.update({k: _rate(v, product) for k, v in _flatten(cfg["product"][product].get("rates", {})).items()})
    return rates


def product_of(device: str) -> str | None:
    """The product row for a device name (`torch.cuda.get_device_properties(...).name`), if the configuration has one."""
    slug = slugify_gpu(device)
    return slug if slug in load()["product"] else None


def quantum(cycles: float) -> int:
    return int(cycles * 256.0 + 0.5)


def _source_findings(where: str, arch: str, rate: Rate) -> list[str]:
    if rate.kind != "measured":
        return [] if rate.where else [f"{where}: a {rate.kind} rate names no source"]
    if not rate.on:
        return [f"{where}: a measured rate names no product it was measured on (`on`)"]
    record = RESULTS / rate.where / f"sm_{cc_of(arch) // 10}.json"
    if not record.is_file():
        return [f"{where}: its lab record {record.relative_to(ROOT)} does not exist"]
    data = json.loads(record.read_text())
    medians = {r["name"]: r["median"] for r in data["results"]}
    findings = []
    if slugify_gpu(data.get("device", "")) != rate.on:
        findings.append(f"{where}: {record.relative_to(ROOT)} was recorded on `{data.get('device')}`, not `{rate.on}`")
    if rate.row not in medians:
        findings.append(f"{where}: {record.relative_to(ROOT)} has no result `{rate.row}`")
    elif abs(rate.cycles - medians[rate.row]) > TOLERANCE * max(1.0, medians[rate.row]):
        findings.append(f"{where}: {rate.cycles} in {CONFIG.name}, {medians[rate.row]:.4f} in {record.relative_to(ROOT)}")
    return findings


def check(cfg: dict | None = None, header_text: str | None = None) -> list[str]:
    """The header current; every built architecture tabulated and able to price a choice; every product on a tabulated
    architecture; every rate a known field with one source that holds."""
    cfg = cfg or load()
    findings = []
    if (HEADER.read_text() if header_text is None else header_text) != header(cfg):
        findings.append(f"{HEADER.relative_to(ROOT)} is not what {CONFIG.name} generates "
                        "(`python -m measure.hardware --write`)")
    names = [f["name"] for f in cfg["schema"]["caps"] if f["name"] != "cc"]
    kinds, taxed = cfg["schema"]["mma"], cfg["schema"]["taxed"]
    known = {*CHOICE, *(f"mma.{k}" for k in kinds), *(f"tax.{k}.{c}" for k in kinds for c in taxed),
             *(f"latency.{k}" for k in cfg["schema"]["latency"]),
             *(f"shared.{k}" for k in cfg["schema"]["shared"]), *(f"pipe.{k}" for k in cfg["schema"]["pipe"]),
             *(f"global.{k}" for k in cfg["schema"]["global"])}
    for arch, row in cfg["arch"].items():
        if sorted(row["caps"]) != sorted(names):
            findings.append(f"{arch}: its capabilities are not the schema's")
        if row.get("build", {}).get("family") not in FAMILIES:
            findings.append(f"{arch}: its build names no family of {', '.join(FAMILIES)}")
        if not set(row.get("build", {})) <= {"family", *BUILD_TRAITS}:
            findings.append(f"{arch}: its build holds a trait outside family, {', '.join(BUILD_TRAITS)}")
    built = sorted({f"sm_{p.stem.removeprefix('sm_')}" for p in MANIFESTS.glob("*/sm_*.json")}, key=cc_of)
    for arch in built:
        if arch not in cfg["arch"]:
            findings.append(f"{arch} is built (tools/manifests) but has no row in {CONFIG.name}")
            continue
        rates = resolve(arch, cfg=cfg)
        missing = [f for f in (*CHOICE, *(f"mma.{k}" for k in kinds)) if f not in rates]
        if missing:
            findings.append(f"{arch} is built but its defaults lack {', '.join(missing)}")
        if cfg["arch"][arch].get("build", {}).get("window", 0) <= 0:
            findings.append(f"{arch} is built but its build chooses no window")
    for product, row in cfg["product"].items():
        if row["arch"] not in cfg["arch"]:
            findings.append(f"product {product} names {row['arch']}, which has no row")
            continue
        if not set(row.get("build", {})) <= set(BUILD_TRAITS):
            findings.append(f"product {product}: its build overrides a trait outside {', '.join(BUILD_TRAITS)}")
        if row.get("build"):
            findings.append(f"product {product}: a build variant is not gated yet -- the oracle set and the SASS gate "
                            f"run one build an architecture (docs/internals/common/hardware.md#builds)")
        if slugify_gpu(row.get("device", "")) != product:
            findings.append(f"product {product}: its device `{row.get('device')}` is not that product")

    scopes = [(arch, f"{arch}", row.get("rates", {}), "") for arch, row in cfg["arch"].items()]
    scopes += [(row["arch"], f"product {p}", row.get("rates", {}), p) for p, row in cfg["product"].items()]
    for arch, scope, rates, on in scopes:
        for field, entry in _flatten(rates).items():
            where = f"{scope} {field}"
            if field not in known:
                findings.append(f"{where}: not a rate the schema names")
            if sum(k in entry for k in SOURCES) != 1:
                findings.append(f"{where}: needs exactly one of {', '.join(SOURCES)}")
                continue
            findings += _source_findings(where, arch, _rate(entry, on))
    return findings


def main() -> int:
    args = sys.argv[1:]
    if "--write" in args:
        HEADER.write_text(header())
        print(f"wrote {HEADER.relative_to(ROOT)}")
        return 0
    if "--check" in args:
        findings = check()
        for f in findings:
            print(f)
        print(f"hardware: {len(findings)} finding(s)")
        return 1 if findings else 0
    cfg = load()
    product = args[args.index("--product") + 1] if "--product" in args else None
    arch = args[args.index("--arch") + 1] if "--arch" in args else None
    targets = ([(None, product)] if product else [(arch, None)] if arch
               else [(None, p) for p in cfg["product"]] + [(a, None) for a in tabulated(cfg)])
    for a, p in targets:
        rates = resolve(a, p, cfg)
        print(p or a)
        for field, r in rates.items():
            source = r.where + (f" / {r.row}" if r.row else "") + (f" (on {r.on})" if r.on else "")
            print(f"  {field:28s} {r.cycles:8.3f}  {r.kind:10s} {source}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

