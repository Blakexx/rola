"""THE GRAPH'S COMPILE FLAGS AND FACTS, as Starlark: `@rola_env//:flags.bzl`, written by the environment repository
with the environment's own interpreter from `tools/build_flags.py` -- the one source of the flag list -- so the graph
states no flag of its own.

`NVCC_FLAGS` are the codegen flags without the `-gencode` targets, which rules_cuda writes from the build's
architectures; `RATIFIED_ARCHS` are the toolchain's ratified manifests, the build's default architectures; `TORCH` and
`CXX11_ABI` are the environment's torch, for the build record. Docs: docs/build-graph.md#compile.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

TOOLS = Path(__file__).resolve().parents[1] / "tools"
sys.path.insert(0, str(TOOLS))
import build_flags  # noqa: E402
import toolchains  # noqa: E402


def _once(flags: list[str]) -> list[str]:
    return list(dict.fromkeys(flags))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("toolchain", type=Path, help="the toolchain record (tools/toolchains/<name>.json)")
    a = ap.parse_args()
    #: host.nvcc_threads, the cicc an nvcc job runs, which the front door hands the environment's repository
    nvcc_threads = int(os.environ["ROLA_NVCC_THREADS"])
    import torch

    archs = toolchains.named(a.toolchain.stem).archs()
    #: the machine's cicc a job, the count the front door's job budget divides by
    nvcc = _once(build_flags.nvcc_flags([], nvcc_threads=nvcc_threads) + list(build_flags.COMMON_NVCC_FLAGS)
                 + build_flags.extension_defines())
    cxx = _once(list(build_flags.HOST_CXX_FLAGS) + build_flags.extension_defines())
    out = ['"""GENERATED by bazel/flags.py from tools/build_flags.py -- do not edit."""', "",
           f"NVCC_FLAGS = {json.dumps(nvcc)}",
           f"HOST_CXX_FLAGS = {json.dumps(cxx)}",
           f"RATIFIED_ARCHS = {json.dumps(archs)}",
           f"TOOLCHAIN = {json.dumps(a.toolchain.stem)}",
           f"TORCH = {json.dumps(torch.__version__)}",
           f"CXX11_ABI = {bool(torch._C._GLIBCXX_USE_CXX11_ABI)}",
           f"TORCH_CUDA = {json.dumps(torch.version.cuda)}", ""]
    sys.stdout.write("\n".join(out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
